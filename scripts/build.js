const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const root = path.resolve(__dirname, '..');
const order = ['core.js', 'catalog.js', 'art.js', 'session.js', 'fullscreen.js', 'games/breakout.js', 'games/memory.js', 'games/runner.js', 'games/snail-model.js', 'games/snail-view.js', 'games/snail-sprites.js', 'games/snail-art.js', 'games/snail-game.js', 'app.js'];
const html = fs.readFileSync(path.join(root, 'src/index.html'), 'utf8');
const css = ['style.css', 'games/snail-style.css', 'games/snail-refined.css', 'fullscreen.css', 'games/snail-interaction.css'].map(file => fs.readFileSync(path.join(root, 'src', file), 'utf8')).join('\n');
const sourceAssets={garden:'garden-fine-v3.png',sprites:'garden-sprites-v4.png'};
const assets=Object.entries(sourceAssets).map(([key,file])=>{
 const data=fs.readFileSync(path.join(root,'src/assets',file));
 const hash=crypto.createHash('sha256').update(data).digest('hex').slice(0,12);
 const prefix=key==='garden'?'garden-fine':'garden-sprites';
 return {key,data,url:`assets/${prefix}-${hash}.png`,name:`${prefix}-${hash}.png`};
});
const scripts = `globalThis.SnailAssets=${JSON.stringify(Object.fromEntries(assets.map(a=>[a.key,a.url])))};\n` + order.map(file => fs.readFileSync(path.join(root, 'src', file), 'utf8')).join('\n');
if (/<\/script/i.test(scripts) || /<\/style/i.test(css)) throw new Error('Unsafe inline closing tag');
const result = html.replace('<!-- STYLES -->', () => `<style>\n${css}\n</style>`).replace('<!-- SCRIPTS -->', () => `<script>\n${scripts}\n</script>`);
const dist = path.join(root, 'dist');
fs.mkdirSync(dist, { recursive: true });
fs.mkdirSync(path.join(dist,'assets'), { recursive: true });
for(const asset of assets)fs.writeFileSync(path.join(dist,'assets',asset.name),asset.data);
fs.writeFileSync(path.join(dist,'assets-manifest.json'),JSON.stringify(assets.map(a=>a.url)));
fs.writeFileSync(path.join(dist, 'index.html'), result);
let standalone=result;
for(const asset of assets)standalone=standalone.replace(asset.url,()=>`data:image/png;base64,${asset.data.toString('base64')}`);
fs.writeFileSync(path.join(dist, 'schneckenkampf.html'), standalone.replace('<body>', '<body><script>if(!location.hash)location.hash="spiel/schneckenkampf";</script>'));
fs.writeFileSync(path.join(dist, '.htaccess'), 'DirectoryIndex index.html\nOptions -Indexes\n<IfModule mod_headers.c>\nHeader set X-Content-Type-Options "nosniff"\nHeader set Referrer-Policy "strict-origin-when-cross-origin"\n</IfModule>\n');
console.log(`Built dist/index.html (${Buffer.byteLength(result)} bytes). No runtime dependencies.`);
