const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const root = path.resolve(__dirname, '..');
const order = ['core.js', 'catalog.js', 'art.js', 'session.js', 'fullscreen.js', 'games/breakout.js', 'games/memory.js', 'games/runner.js', 'games/snail-model.js', 'games/snail-art.js', 'games/snail-game.js', 'app.js'];
const html = fs.readFileSync(path.join(root, 'src/index.html'), 'utf8');
const css = ['style.css', 'games/snail-style.css', 'games/snail-refined.css', 'fullscreen.css'].map(file => fs.readFileSync(path.join(root, 'src', file), 'utf8')).join('\n');
const asset = fs.readFileSync(path.join(root, 'src/assets/garden-fine-v3.png'));
const assetName = `garden-fine-${crypto.createHash('sha256').update(asset).digest('hex').slice(0,12)}.png`;
const assetURL = `assets/${assetName}`;
const scripts = `globalThis.SnailAssets=${JSON.stringify({garden:assetURL})};\n` + order.map(file => fs.readFileSync(path.join(root, 'src', file), 'utf8')).join('\n');
if (/<\/script/i.test(scripts) || /<\/style/i.test(css)) throw new Error('Unsafe inline closing tag');
const result = html.replace('<!-- STYLES -->', () => `<style>\n${css}\n</style>`).replace('<!-- SCRIPTS -->', () => `<script>\n${scripts}\n</script>`);
const dist = path.join(root, 'dist');
fs.mkdirSync(dist, { recursive: true });
fs.mkdirSync(path.join(dist,'assets'), { recursive: true });
fs.writeFileSync(path.join(dist,'assets',assetName),asset);
fs.writeFileSync(path.join(dist,'assets-manifest.json'),JSON.stringify([assetURL]));
fs.writeFileSync(path.join(dist, 'index.html'), result);
const standalone=result.replace(assetURL,()=>`data:image/png;base64,${asset.toString('base64')}`);
fs.writeFileSync(path.join(dist, 'schneckenkampf.html'), standalone.replace('<body>', '<body><script>if(!location.hash)location.hash="spiel/schneckenkampf";</script>'));
fs.writeFileSync(path.join(dist, '.htaccess'), 'DirectoryIndex index.html\nOptions -Indexes\n<IfModule mod_headers.c>\nHeader set X-Content-Type-Options "nosniff"\nHeader set Referrer-Policy "strict-origin-when-cross-origin"\n</IfModule>\n');
console.log(`Built dist/index.html (${Buffer.byteLength(result)} bytes). No runtime dependencies.`);
